const agent = (id: string) => {
  const found = seedAgents.find((a) => a.id === id);
  if (!found) throw new Error(`Unknown seed agent ${id}`);
  return { id: found.id, displayName: found.displayName, city: found.city, registration: found.registration };
};

const dep = (pkg: string, n: number, departsOn: string, returnsOn: string, seatsNote?: string, status: Departure["status"] = "open"): Departure => ({
  id: `${pkg}-d${n}`,
  departsOn,
  returnsOn,
  seatsNote,
  status,
});

